"""Builds TreeGuardian_CommandBar.lua: BuildModel.lua with the scripts it installs embedded.

Run from anywhere: python3 TreeGuardian/tools/bundle.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "TreeGuardian_CommandBar.lua"


def long_string(text):
    level = 1
    while ("]" + "=" * level + "]") in text:
        level += 1
    eq = "=" * level
    return "[" + eq + "[\n" + text + "]" + eq + "]"


def main():
    builder = (ROOT / "src" / "BuildModel.lua").read_text()

    def embed(match):
        source = (ROOT / match.group(2)).read_text()
        return match.group(1) + long_string(source)

    bundled, count = re.subn(r"^(local \w+ = )nil -- @bundle (\S+)$", embed, builder, flags=re.M)
    assert count == 2, f"expected 2 @bundle lines, found {count}"
    header = (
        "-- GENERATED by tools/bundle.py from src/. Edit the files in src/, then re-run the bundler.\n"
        "-- Paste this whole file into Roblox Studio's Command Bar and press Enter.\n"
    )
    OUT.write_text(header + bundled)
    print(f"wrote {OUT.relative_to(ROOT.parent)}")


if __name__ == "__main__":
    main()
